def get_roi_category(roi_name: str) -> str:
    """
    獲取 ROI 所屬的功能分類
    
    Args:
        roi_name: ROI 名稱
    
    Returns:
        功能分類名稱
    """
    for category, rois in ROI_CATEGORIES.items():
        if roi_name in rois:
            return category
    return "其他"
