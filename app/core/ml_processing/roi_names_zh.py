def get_roi_display_name(roi_name: str, language: str = "zh") -> str:
    """
    獲取 ROI 的顯示名稱
    
    Args:
        roi_name: 英文 ROI 名稱
        language: 語言 ("zh" 或 "en")
    
    Returns:
        顯示名稱
    """
    if language == "zh":
        return ROI_NAMES_ZH.get(roi_name, roi_name)
    else:
        return roi_name


def get_roi_bilingual_name(roi_name: str) -> str:
    """
    獲取 ROI 的雙語名稱
    
    Args:
        roi_name: 英文 ROI 名稱
    
    Returns:
        中英文雙語名稱
    """
    zh_name = ROI_NAMES_ZH.get(roi_name, roi_name)
    if zh_name != roi_name:
        return f"{zh_name} ({roi_name})"
    else:
        return roi_name


